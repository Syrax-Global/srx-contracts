/**
 * addresses.js — docs/ADDRESSES.md, the one place deployed addresses are published.
 *
 *   node scripts/docs/addresses.js          (rewrites docs/ADDRESSES.md)
 *
 * Generated from the deployment records deployments/<network>.json, which the deploy
 * scripts write. ⛔ Before this file existed (GitHub Standards, 1 Oct 2026) the README
 * said "take addresses only from this repository" while the overview and the runbook
 * listed May's superseded Sepolia addresses as "Deployed & Verified". Every document now
 * links here instead of repeating an address, and test/AddressesDoc.test.js fails if this
 * file and the records disagree, or if another document lists an address of its own.
 *
 * Test networks only: there is no mainnet deployment.
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..", "..");
const OUT = path.join(ROOT, "docs", "ADDRESSES.md");
const DIR = path.join(ROOT, "deployments");

// Source commits whose deployments predate REG-50/53/54 and the 16 Oct 2026 internal-audit
// fixes. While any listed deployment comes from one, the page says so: the contracts at
// those addresses do not behave like the current code. Remove an entry once redeployed.
const PRE_FIX_COMMITS = ["0deaa30"];

const NETWORKS = {
  sepolia:    { title: "Ethereum Sepolia (the hub)", explorer: "https://sepolia.etherscan.io/address/" },
  bscTestnet: { title: "BNB Chain testnet (a spoke)", explorer: "https://testnet.bscscan.com/address/" },
};

function records() {
  return Object.keys(NETWORKS)
    .filter((n) => fs.existsSync(path.join(DIR, `${n}.json`)))
    .map((n) => ({ net: n, ...JSON.parse(fs.readFileSync(path.join(DIR, `${n}.json`), "utf8")) }));
}

function render() {
  const L = [];
  L.push("# Deployed addresses");
  L.push("");
  L.push("<!-- Generated by scripts/docs/addresses.js from deployments/<network>.json. Do not edit. -->");
  L.push("");
  L.push("⚠️ **Test networks only. SRX is not deployed on any mainnet.** These contracts hold test tokens with no value.");
  L.push("Take contract addresses only from this file or from [syrax.global](https://www.syrax.global), never from a third party.");
  L.push("");
  if (records().some((r) => PRE_FIX_COMMITS.some((c) => (r.commit || "").startsWith(c)))) {
    L.push("⚠️ **The testnet contracts listed here were deployed on 7 October 2026, before REG-50, REG-53 and REG-54 and before the 16 October 2026 internal-audit fixes, and they will be redeployed.** They still have the old design (upgradeable proxies, the staking bonus stream, `receiveFees`, `recoverLiquidity`, settable fee limits, a circuit breaker that pauses the token) and none of the 16 October fixes. Do not read their behaviour as the current code's. This list will be regenerated when the fixed code is deployed.");
    L.push("");
  }
  for (const r of records()) {
    const { title, explorer } = NETWORKS[r.net];
    const link = (a) => `[\`${a}\`](${explorer}${a})`;
    L.push(`## ${title}`);
    L.push("");
    L.push(`Chain id ${r.chainId} · deployed ${r.deployedAt.slice(0, 10)}${r.fromBlock ? ` from block ${r.fromBlock}` : ""}` +
      `${r.commit ? ` · source commit \`${r.commit}\`` : ""} · deployer ${link(r.deployer)}`);
    L.push("");
    const groups = [["Contracts", r.contracts], ["Vesting vaults", r.vaults], ["Launch wallets (test placeholders)", r.wallets]];
    for (const [heading, group] of groups) {
      if (!group || Object.keys(group).length === 0) continue;
      L.push(`| ${heading} | Address |`);
      L.push("|---|---|");
      for (const [name, addr] of Object.entries(group)) L.push(`| ${name} | ${link(addr)} |`);
      L.push("");
    }
  }
  return L.join("\n");
}

if (require.main === module) {
  fs.writeFileSync(OUT, render());
  console.log(`wrote ${path.relative(ROOT, OUT)}`);
}

module.exports = { render, records, OUT };
